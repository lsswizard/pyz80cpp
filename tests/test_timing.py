    def test_instruction_timing(self, cpu, name, code, cycles, setup):
        if setup == "IX":
            cpu.registers.IX = 0x1000
            addr = 0x1010
            cpu.write_byte(addr, 0x00)
        elif setup == "IY":
            cpu.registers.IY = 0x1000
            addr = 0x1010
            cpu.write_byte(addr, 0x00)
        elif setup == "B=2":
            cpu.registers.B = 2
        elif setup == "B=1":
            cpu.registers.B = 1
        elif setup == "FLAG_Z":
            cpu.registers.F = 0x40
        elif setup == "FLAG_C":
            cpu.registers.F = 0x01

        for i, b in enumerate(code):
            cpu.write_byte(i, b)
        cpu.registers.PC = 0

        actual_cycles = cpu.step()

        assert actual_cycles == cycles, (
            f"{name}: expected {cycles} cycles, got {actual_cycles}"
        )
